import "math"

// j2000 is the Julian date of J2000.0 and millennium the days in a Julian
// millennium, the unit of the time argument tau.
const (
	j2000      = 2451545.0
	millennium = 365250.0
)

// Term is one periodic term A cos(B + C tau), with A in radians or
// astronomical units, B in radians, and C in radians per Julian millennium.
type Term struct{ A, B, C float64 }

// Body holds the three VSOP87D variables of one body, each a list of series
// indexed by the power of tau that multiplies it. The tables are generated by
// internal/cmd/genvsop.
type Body struct {
	L, B, R [][]Term
}

// Heliocentric returns the body's heliocentric ecliptic longitude, in degrees
// in [0, 360), latitude in degrees, and radius vector in astronomical units, at
// the given Julian ephemeris day, referred to the dynamical ecliptic and
// equinox of date.
func (v *Body) Heliocentric(jde float64) (lonDeg, latDeg, radiusAU float64) {
	tau := Millennia(jde)
	l := Sum(v.L, tau)
	b := Sum(v.B, tau)
	r := Sum(v.R, tau)
	lonDeg = math.Mod(l*180/math.Pi, 360)
	if lonDeg < 0 {
		lonDeg += 360
	}
	return lonDeg, b * 180 / math.Pi, r
}

// Sum evaluates the sum over alpha of tau^alpha times the sum of
// A cos(B + C tau) over the terms of series[alpha], by Horner's rule in tau.
func Sum(series [][]Term, tau float64) float64 {
	var total float64
	for alpha := len(series) - 1; alpha >= 0; alpha-- {
		var s float64
		for _, t := range series[alpha] {
			s += t.A * math.Cos(t.B+t.C*tau)
		}
		total = total*tau + s
	}
	return total
}

// Millennia returns the Julian millennia from J2000.0 to the given Julian
// ephemeris day, the time argument tau of VSOP87.
func Millennia(jde float64) float64 {
	return (jde - j2000) / millennium
}
