// Package vsop87 evaluates the VSOP87 planetary theory: the series types the
// generated tables are written in, and the sum that turns a table into a
// heliocentric position. It holds no tables itself; each body's table lives in
// the package that needs it, so a program links only the tables it imports.
//
// The theory is P. Bretagnon and G. Francou, "Planetary theories in
// rectangular and spherical variables. VSOP87 solutions", Astronomy and
// Astrophysics 202, 309 (1988). Version D gives heliocentric ecliptic
// longitude, latitude, and radius referred to the dynamical ecliptic and
// equinox of date, in radians and astronomical units, as Poisson series in
// Julian millennia of TDB from J2000.0.
